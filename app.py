"""
app.py — Persona Chatbot (Historical Figure)
Problem Statement #16 — GenAI Mini Project

Streamlit chat application that lets the user converse with one of six
historical figures via the Google Gemini API (gemini-2.5-flash).

Safeguards:
  - Persistent "AI Role-Play Simulation" banner on the main interface.
  - AI-role-play notice inside the active persona card.
  - Per-persona conversation history in st.session_state.
  - Graceful error handling for missing API key, rate limits, and API errors.
"""

import os

import streamlit as st
from dotenv import load_dotenv
from google import genai
from google.genai import types

from personas import get_persona, get_persona_list, get_starter_questions

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
load_dotenv()

MODEL_ID = "gemini-2.5-flash"
BANNER_TEXT = "AI Role-Play Simulation — Responses are generated by AI for educational purposes"
PERSONA_KEY = "selected_persona_key"
HISTORY_KEY = "chat_histories"

st.set_page_config(
    page_title="Persona Chatbot — Historical Figures",
    page_icon="🏛️",
    layout="wide",
)


# ---------------------------------------------------------------------------
# Gemini client wrapper
# ---------------------------------------------------------------------------
@st.cache_resource
def get_client() -> genai.Client | None:
    """Build the Gemini client once. Returns None if the key is missing."""
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        return None
    return genai.Client(api_key=api_key)


def call_gemini(client: genai.Client, system_prompt: str,
                conversation: list[dict]) -> str:
    """Send the persona system prompt + conversation to Gemini and return
    the assistant reply. Raises a friendly ValueError on known failures."""
    contents = [
        types.Content(
            role=("model" if msg["role"] == "assistant" else "user"),
            parts=[types.Part(text=msg["content"])],
        )
        for msg in conversation
        if msg.get("content")
    ]
    response = client.models.generate_content(
        model=MODEL_ID,
        contents=contents,
        config=types.GenerateContentConfig(
            system_instruction=system_prompt,
            temperature=0.7,
        ),
    )
    text = (response.text or "").strip()
    if not text:
        raise ValueError("The model returned an empty response. Please try again.")
    return text


def friendly_api_error(exc: Exception) -> str:
    """Map common Gemini API errors to actionable guidance."""
    msg = str(exc).lower()
    if "api key" in msg or "unauthenticated" in msg or "401" in msg or "403" in msg:
        return (
            "GEMINI_API_KEY appears to be missing or invalid. "
            "Check your .env file (see .env.example) and restart the app."
        )
    if "429" in msg or "rate" in msg or "quota" in msg or "resource_exhausted" in msg:
        return (
            "The Gemini API rate limit was reached. Wait a few seconds "
            "and try again."
        )
    if "503" in msg or "unavailable" in msg:
        return "The Gemini service is temporarily unavailable. Please retry shortly."
    return f"An unexpected API error occurred: {exc}"


# ---------------------------------------------------------------------------
# Session state helpers
# ---------------------------------------------------------------------------
def init_state():
    if PERSONA_KEY not in st.session_state:
        st.session_state[PERSONA_KEY] = "shivaji"
    if HISTORY_KEY not in st.session_state:
        st.session_state[HISTORY_KEY] = {}


def histories(key: str) -> list[dict]:
    """Return (creating if needed) the chat history for a persona."""
    return st.session_state[HISTORY_KEY].setdefault(key, [])


def reset_current_chat():
    key = st.session_state[PERSONA_KEY]
    st.session_state[HISTORY_KEY][key] = []
    st.rerun()


# ---------------------------------------------------------------------------
# UI — Sidebar
# ---------------------------------------------------------------------------
init_state()

persona_list = get_persona_list()
persona_names = {p["name"]: p["key"] for p in persona_list}
key_to_persona = {p["key"]: p for p in persona_list}

with st.sidebar:
    st.title("🏛️ Persona Chatbot")
    st.caption("Problem Statement #16 — Historical Figure Role-Play")

    st.subheader("Choose a Historical Figure")
    current_key = st.session_state[PERSONA_KEY]
    selected_name = st.selectbox(
        "Persona",
        list(persona_names.keys()),
        index=list(persona_names).index(key_to_persona[current_key]["name"]),
        label_visibility="collapsed",
    )
    selected_key = persona_names[selected_name]

    # Clean context switch when the persona changes
    if selected_key != current_key:
        st.session_state[PERSONA_KEY] = selected_key
        st.rerun()

    st.divider()
    if st.button("🗑️ Clear Chat", use_container_width=True, on_click=None):
        st.session_state[HISTORY_KEY][selected_key] = []
        st.rerun()

    st.divider()
    st.markdown(
        "**Disclaimer**  \nThis is an AI role-play simulation for "
        "educational purposes. The persona's views and statements are "
        "model-generated and may not be historically complete."
    )

persona = get_persona(selected_key)
history = histories(selected_key)

# ---------------------------------------------------------------------------
# UI — Main chat area
# ---------------------------------------------------------------------------
st.title(f"🏛️ Converse with {persona['name']}")

# Mandatory persistent banner
st.error(f"⚠️ **{BANNER_TEXT}**")

# Persona card (with in-card AI notice)
with st.container(border=True):
    col1, col2 = st.columns([1, 3])
    col1.markdown("### 🎭")
    col2.markdown(f"### {persona['name']}")
    col2.caption(
        f"**{persona['title']}** · {persona['era']}"
    )
    col2.markdown(persona["short_bio"])
    col2.markdown(
        f"*🤖 {BANNER_TEXT}.*"
    )

st.divider()

# ---------------------------------------------------------------------------
# Chat rendering + input
# ---------------------------------------------------------------------------
client = get_client()

for msg in history:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])

if len(history) == 0:
    st.info(
        "Start your conversation below, or click one of the suggested "
        "starter questions to begin immediately."
    )

# Suggested starter questions
with st.container():
    st.markdown("**💡 Suggested Starter Questions**")
    cols = st.columns(2)
    for i, question in enumerate(get_starter_questions(selected_key)):
        if cols[i % 2].button(question, key=f"starter_{selected_key}_{i}"):
            history.append({"role": "user", "content": question})
            st.rerun()

st.divider()

user_input = st.chat_input("Ask your question…")

if user_input:
    if client is None:
        st.error(
            "GEMINI_API_KEY is not set. Copy `.env.example` to `.env`, "
            "add your key, and restart the app."
        )
    else:
        history.append({"role": "user", "content": user_input})
        with st.chat_message("user"):
            st.markdown(user_input)
        with st.chat_message("assistant"):
            with st.spinner(f"{persona['name']} is reflecting…"):
                try:
                    reply = call_gemini(client, persona["system_prompt"], history)
                except Exception as exc:
                    reply = friendly_api_error(exc)
                    st.error(reply)
                    history.append({"role": "assistant", "content": reply})
                else:
                    st.markdown(reply)
                    history.append({"role": "assistant", "content": reply})
